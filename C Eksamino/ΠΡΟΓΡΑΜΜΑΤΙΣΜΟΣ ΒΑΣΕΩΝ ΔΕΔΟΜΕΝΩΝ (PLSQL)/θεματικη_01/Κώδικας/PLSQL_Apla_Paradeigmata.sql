-- ΠΡΩΤΑ ΠΑΡΑΔΕΙΓΜΑΤΑ PL/SQL
-- Εκπαιδευτικό αρχείο για αρχάριους
--
-- ΑΝΟΙΓΜΑ: SQL Developer > File > Open > αυτό το αρχείο.
-- Επίλεξε την υπάρχουσα σύνδεσή σου στο Worksheet.
-- ΟΛΑ ΜΑΖΙ: χωρίς επιλεγμένο κείμενο, πάτησε F5.
-- ΕΝΑ ΠΑΡΑΔΕΙΓΜΑ: εκτέλεσε πρώτα το SET SERVEROUTPUT ON;
-- και μετά επίλεξε ολόκληρο το παράδειγμα από DECLARE ή BEGIN
-- μέχρι και την τελική / και πάτησε F5.
-- Τα παραδείγματα είναι ανεξάρτητα. Δεν χρειάζονται πίνακες.
-- Δεν δημιουργούν ή αλλάζουν δεδομένα στη βάση.
-- Κάθε block έχει δικό του χώρο μεταβλητών.
-- Το / μόνο του στη γραμμή εκτελεί το προηγούμενο block.
-- Τα αναμενόμενα αποτελέσματα παρακάτω είναι σχόλια, όχι πραγματική καταγραφή.
-- Δούλεψε μία ενότητα τη φορά· οι τελευταίες ενότητες είναι επόμενα μαθήματα.
--
SET SERVEROUTPUT ON;

-- =================================================================
-- ΕΝΟΤΗΤΑ Α Μηνύματα και σχόλια
-- =================================================================

-- ΠΑΡΑΔΕΙΓΜΑ 01: Ένα μήνυμα
-- Η PUT_LINE εμφανίζει κείμενο και αλλάζει γραμμή.
-- Αναμενόμενο: Γεια σου!
BEGIN
    DBMS_OUTPUT.PUT_LINE('Γεια σου!');
END;
/

-- ΠΑΡΑΔΕΙΓΜΑ 02: Πολλά μηνύματα
-- Οι εντολές εκτελούνται από πάνω προς τα κάτω.
-- Αναμενόμενο: Τρία μηνύματα σε τρεις γραμμές.
BEGIN
    DBMS_OUTPUT.PUT_LINE('Με λένε Γιάννη.');
    DBMS_OUTPUT.PUT_LINE('Μαθαίνω PL/SQL.');
    DBMS_OUTPUT.PUT_LINE('Ξεκινάμε!');
END;
/

-- ΠΑΡΑΔΕΙΓΜΑ 03: Σχόλια
-- Το -- αφορά μία γραμμή. Το /* ... */ αφορά πολλές γραμμές.
-- Αναμενόμενο: Τα σχόλια εξηγούν τον κώδικα.
BEGIN
    -- Αυτό το σχόλιο δεν εκτελείται.
    /* Ούτε αυτό το σχόλιο εκτελείται.
       Μπορεί να έχει πολλές γραμμές. */
    DBMS_OUTPUT.PUT_LINE('Τα σχόλια εξηγούν τον κώδικα.');
END;
/

-- ΠΑΡΑΔΕΙΓΜΑ 04: Ένωση κειμένων
-- Το || ενώνει κείμενα. Το κενό μέσα στα εισαγωγικά είναι μέρος του κειμένου.
-- Αναμενόμενο: Γεια σου, Γιάννη!
BEGIN
    DBMS_OUTPUT.PUT_LINE('Γεια σου, ' || 'Γιάννη!');
END;
/

-- =================================================================
-- ΕΝΟΤΗΤΑ Β Αριθμοί και πράξεις
-- =================================================================

-- ΠΑΡΑΔΕΙΓΜΑ 05: Πρόσθεση
-- Αριθμοί χωρίς εισαγωγικά: υπολογίζουμε και εμφανίζουμε το αποτέλεσμα.
-- Αναμενόμενο: 15
BEGIN
    DBMS_OUTPUT.PUT_LINE(10 + 5);
END;
/

-- ΠΑΡΑΔΕΙΓΜΑ 06: Αφαίρεση
-- Αριθμοί χωρίς εισαγωγικά: υπολογίζουμε και εμφανίζουμε το αποτέλεσμα.
-- Αναμενόμενο: 5
BEGIN
    DBMS_OUTPUT.PUT_LINE(10 - 5);
END;
/

-- ΠΑΡΑΔΕΙΓΜΑ 07: Πολλαπλασιασμός
-- Αριθμοί χωρίς εισαγωγικά: υπολογίζουμε και εμφανίζουμε το αποτέλεσμα.
-- Αναμενόμενο: 50
BEGIN
    DBMS_OUTPUT.PUT_LINE(10 * 5);
END;
/

-- ΠΑΡΑΔΕΙΓΜΑ 08: Διαίρεση
-- Αριθμοί χωρίς εισαγωγικά: υπολογίζουμε και εμφανίζουμε το αποτέλεσμα.
-- Αναμενόμενο: 2
BEGIN
    DBMS_OUTPUT.PUT_LINE(10 / 5);
END;
/

-- ΠΑΡΑΔΕΙΓΜΑ 09: Υπόλοιπο διαίρεσης
-- Αριθμοί χωρίς εισαγωγικά: υπολογίζουμε και εμφανίζουμε το αποτέλεσμα.
-- Αναμενόμενο: 1
BEGIN
    DBMS_OUTPUT.PUT_LINE(MOD(10, 3));
END;
/

-- ΠΑΡΑΔΕΙΓΜΑ 10: Προτεραιότητα πράξεων
-- Αριθμοί χωρίς εισαγωγικά: υπολογίζουμε και εμφανίζουμε το αποτέλεσμα.
-- Αναμενόμενο: 20
BEGIN
    DBMS_OUTPUT.PUT_LINE((2 + 3) * 4);
END;
/

-- ΠΑΡΑΔΕΙΓΜΑ 11: Κείμενο και αποτέλεσμα
-- Οι παρενθέσεις ομαδοποιούν την πράξη. Η TO_CHAR μετατρέπει τον αριθμό σε κείμενο.
-- Αναμενόμενο: Άθροισμα: 15
BEGIN
    DBMS_OUTPUT.PUT_LINE('Άθροισμα: ' || TO_CHAR(10 + 5));
END;
/

-- =================================================================
-- ΕΝΟΤΗΤΑ Γ Μεταβλητές
-- =================================================================

-- ΠΑΡΑΔΕΙΓΜΑ 12: Μεταβλητή κειμένου
-- Το DECLARE αρχίζει τις δηλώσεις. VARCHAR2(50 CHAR): κείμενο έως 50 χαρακτήρες. Το := δίνει τιμή.
-- Αναμενόμενο: Γιάννης
DECLARE
    v_name VARCHAR2(50 CHAR) := 'Γιάννης';
BEGIN
    DBMS_OUTPUT.PUT_LINE(v_name);
END;
/

-- ΠΑΡΑΔΕΙΓΜΑ 13: Μεταβλητή αριθμού
-- NUMBER: αριθμητικός τύπος. Το v_age είναι όνομα που επιλέγουμε εμείς.
-- Αναμενόμενο: Ηλικία: 20
DECLARE
    v_age NUMBER := 20;
BEGIN
    DBMS_OUTPUT.PUT_LINE('Ηλικία: ' || TO_CHAR(v_age));
END;
/

-- ΠΑΡΑΔΕΙΓΜΑ 14: Αλλαγή τιμής
-- Μια μεταβλητή μπορεί να αποκτήσει νέα τιμή μέσα στο BEGIN.
-- Αναμενόμενο: 10 και μετά 15
DECLARE
    v_score NUMBER := 10;
BEGIN
    DBMS_OUTPUT.PUT_LINE(v_score);
    v_score := 15;
    DBMS_OUTPUT.PUT_LINE(v_score);
END;
/

-- ΠΑΡΑΔΕΙΓΜΑ 15: Αύξηση κατά ένα
-- Διαβάζουμε την παλιά τιμή, προσθέτουμε 1 και αποθηκεύουμε τη νέα.
-- Αναμενόμενο: 2
DECLARE
    v_count NUMBER := 1;
BEGIN
    v_count := v_count + 1;
    DBMS_OUTPUT.PUT_LINE(v_count);
END;
/

-- ΠΑΡΑΔΕΙΓΜΑ 16: Άθροισμα δύο μεταβλητών
-- Μπορούμε να δηλώσουμε αποτέλεσμα χωρίς αρχική τιμή και να του δώσουμε τιμή αργότερα.
-- Αναμενόμενο: 20
DECLARE
    v_a NUMBER := 8;
    v_b NUMBER := 12;
    v_total NUMBER;
BEGIN
    v_total := v_a + v_b;
    DBMS_OUTPUT.PUT_LINE(v_total);
END;
/

-- ΠΑΡΑΔΕΙΓΜΑ 17: Μέσος όρος
-- Οι παρενθέσεις εξασφαλίζουν ότι προσθέτουμε πριν διαιρέσουμε.
-- Αναμενόμενο: 16
DECLARE
    v_grade1 NUMBER := 14;
    v_grade2 NUMBER := 18;
BEGIN
    DBMS_OUTPUT.PUT_LINE((v_grade1 + v_grade2) / 2);
END;
/

-- ΠΑΡΑΔΕΙΓΜΑ 18: Σταθερά
-- Το CONSTANT δηλώνει τιμή που δεν μπορούμε να αλλάξουμε στη συνέχεια.
-- Αναμενόμενο: Ημέρες εβδομάδας: 7
DECLARE
    c_days CONSTANT NUMBER := 7;
BEGIN
    DBMS_OUTPUT.PUT_LINE('Ημέρες εβδομάδας: ' || TO_CHAR(c_days));
END;
/

-- =================================================================
-- ΕΝΟΤΗΤΑ Δ Συνθήκες
-- =================================================================

-- ΠΑΡΑΔΕΙΓΜΑ 19: Απλό IF
-- IF σημαίνει αν. Αν η συνθήκη είναι αληθής, εκτελείται το τμήμα μετά το THEN.
-- Αναμενόμενο: Ενήλικος
DECLARE
    v_age NUMBER := 20;
BEGIN
    IF v_age >= 18 THEN
        DBMS_OUTPUT.PUT_LINE('Ενήλικος');
    END IF;
END;
/

-- ΠΑΡΑΔΕΙΓΜΑ 20: IF και ELSE
-- Το ELSE εκτελείται όταν η συνθήκη δεν ισχύει.
-- Αναμενόμενο: Χρειάζεται επανάληψη.
DECLARE
    v_grade NUMBER := 8;
BEGIN
    IF v_grade >= 10 THEN
        DBMS_OUTPUT.PUT_LINE('Πέρασες!');
    ELSE
        DBMS_OUTPUT.PUT_LINE('Χρειάζεται επανάληψη.');
    END IF;
END;
/

-- ΠΑΡΑΔΕΙΓΜΑ 21: Πολλές περιπτώσεις με ELSIF
-- Ελέγχουμε τις συνθήκες με σειρά. Εκτελείται η πρώτη περίπτωση που ισχύει.
-- Αναμενόμενο: Μηδέν
DECLARE
    v_number NUMBER := 0;
BEGIN
    IF v_number > 0 THEN
        DBMS_OUTPUT.PUT_LINE('Θετικός');
    ELSIF v_number < 0 THEN
        DBMS_OUTPUT.PUT_LINE('Αρνητικός');
    ELSE
        DBMS_OUTPUT.PUT_LINE('Μηδέν');
    END IF;
END;
/

-- ΠΑΡΑΔΕΙΓΜΑ 22: Άρτιος ή περιττός
-- Άρτιος αριθμός έχει υπόλοιπο 0 όταν διαιρείται με το 2. Το = συγκρίνει, το := αναθέτει.
-- Αναμενόμενο: Άρτιος
DECLARE
    v_number NUMBER := 12;
BEGIN
    IF MOD(v_number, 2) = 0 THEN
        DBMS_OUTPUT.PUT_LINE('Άρτιος');
    ELSE
        DBMS_OUTPUT.PUT_LINE('Περιττός');
    END IF;
END;
/

-- ΠΑΡΑΔΕΙΓΜΑ 23: AND
-- AND: πρέπει να ισχύουν και οι δύο συνθήκες.
-- Αναμενόμενο: Βαθμός από 10 έως 20
DECLARE
    v_grade NUMBER := 20;
BEGIN
    IF v_grade >= 10 AND v_grade <= 20 THEN
        DBMS_OUTPUT.PUT_LINE('Βαθμός από 10 έως 20');
    END IF;
END;
/

-- ΠΑΡΑΔΕΙΓΜΑ 24: OR
-- OR: αρκεί να ισχύει μία συνθήκη.
-- Αναμενόμενο: Ακραία βαθμολογία
DECLARE
    v_grade NUMBER := 20;
BEGIN
    IF v_grade = 0 OR v_grade = 20 THEN
        DBMS_OUTPUT.PUT_LINE('Ακραία βαθμολογία');
    END IF;
END;
/

-- ΠΑΡΑΔΕΙΓΜΑ 25: NOT
-- NOT: αντιστρέφει τη λογική τιμή της συνθήκης.
-- Αναμενόμενο: Βαθμός τουλάχιστον 10
DECLARE
    v_grade NUMBER := 20;
BEGIN
    IF NOT (v_grade < 10) THEN
        DBMS_OUTPUT.PUT_LINE('Βαθμός τουλάχιστον 10');
    END IF;
END;
/

-- ΠΑΡΑΔΕΙΓΜΑ 26: Έλεγχος NULL
-- NULL: απουσία τιμής. Ελέγχουμε με IS NULL, όχι με = NULL.
-- Αναμενόμενο: Δεν δόθηκε όνομα.
DECLARE
    v_name VARCHAR2(50 CHAR);
BEGIN
    IF v_name IS NULL THEN
        DBMS_OUTPUT.PUT_LINE('Δεν δόθηκε όνομα.');
    END IF;
END;
/

-- =================================================================
-- ΕΝΟΤΗΤΑ Ε Επαναλήψεις
-- =================================================================

-- ΠΑΡΑΔΕΙΓΜΑ 27: FOR από 1 έως 5
-- Το i δημιουργείται αυτόματα ως μετρητής. Το 1..5 περιλαμβάνει και το 1 και το 5.
-- Αναμενόμενο: 1, 2, 3, 4, 5 σε ξεχωριστές γραμμές
BEGIN
    FOR i IN 1..5 LOOP
        DBMS_OUTPUT.PUT_LINE(i);
    END LOOP;
END;
/

-- ΠΑΡΑΔΕΙΓΜΑ 28: Αντίστροφη FOR
-- Το REVERSE με όρια 1..5 μετρά από 5 προς 1.
-- Αναμενόμενο: 5, 4, 3, 2, 1 σε ξεχωριστές γραμμές
BEGIN
    FOR i IN REVERSE 1..5 LOOP
        DBMS_OUTPUT.PUT_LINE(i);
    END LOOP;
END;
/

-- ΠΑΡΑΔΕΙΓΜΑ 29: Προπαίδεια του 3
-- Σε κάθε επανάληψη αλλάζει η τιμή του i.
-- Αναμενόμενο: Από 3 x 1 = 3 έως 3 x 10 = 30
BEGIN
    FOR i IN 1..10 LOOP
        DBMS_OUTPUT.PUT_LINE('3 x ' || TO_CHAR(i) || ' = ' || TO_CHAR(3 * i));
    END LOOP;
END;
/

-- ΠΑΡΑΔΕΙΓΜΑ 30: Άθροισμα από 1 έως 5
-- Ο συσσωρευτής ξεκινά από 0. Σε κάθε επανάληψη προσθέτουμε τον τρέχοντα αριθμό.
-- Αναμενόμενο: 15
DECLARE
    v_total NUMBER := 0;
BEGIN
    FOR i IN 1..5 LOOP
        v_total := v_total + i;
    END LOOP;
    DBMS_OUTPUT.PUT_LINE(v_total);
END;
/

-- ΠΑΡΑΔΕΙΓΜΑ 31: WHILE
-- Επαναλαμβάνει όσο ισχύει η συνθήκη. Αυξάνουμε τον μετρητή για να τερματίσει.
-- Αναμενόμενο: 1, 2, 3 σε ξεχωριστές γραμμές
DECLARE
    v_count NUMBER := 1;
BEGIN
    WHILE v_count <= 3 LOOP
        DBMS_OUTPUT.PUT_LINE(v_count);
        v_count := v_count + 1;
    END LOOP;
END;
/

-- ΠΑΡΑΔΕΙΓΜΑ 32: LOOP και EXIT WHEN
-- Το EXIT WHEN σταματά την επανάληψη όταν ισχύσει η συνθήκη.
-- Αναμενόμενο: 1, 2, 3 σε ξεχωριστές γραμμές
DECLARE
    v_count NUMBER := 1;
BEGIN
    LOOP
        DBMS_OUTPUT.PUT_LINE(v_count);
        v_count := v_count + 1;
        EXIT WHEN v_count > 3;
    END LOOP;
END;
/

-- =================================================================
-- ΕΝΟΤΗΤΑ ΣΤ Απλές συναρτήσεις
-- =================================================================

-- ΠΑΡΑΔΕΙΓΜΑ 33: Κεφαλαία
-- UPPER: μετατρέπει το κείμενο σε κεφαλαία.
-- Αναμενόμενο: HELLO
BEGIN
    DBMS_OUTPUT.PUT_LINE(UPPER('hello'));
END;
/

-- ΠΑΡΑΔΕΙΓΜΑ 34: Πεζά
-- LOWER: μετατρέπει το κείμενο σε πεζά.
-- Αναμενόμενο: hello
BEGIN
    DBMS_OUTPUT.PUT_LINE(LOWER('HELLO'));
END;
/

-- ΠΑΡΑΔΕΙΓΜΑ 35: Μήκος κειμένου
-- LENGTH: μετρά τους χαρακτήρες.
-- Αναμενόμενο: 6
BEGIN
    DBMS_OUTPUT.PUT_LINE(LENGTH('Oracle'));
END;
/

-- ΠΑΡΑΔΕΙΓΜΑ 36: Τμήμα κειμένου
-- SUBSTR: αρχίζει από θέση 1 και παίρνει 3 χαρακτήρες.
-- Αναμενόμενο: Ora
BEGIN
    DBMS_OUTPUT.PUT_LINE(SUBSTR('Oracle', 1, 3));
END;
/

-- ΠΑΡΑΔΕΙΓΜΑ 37: Αφαίρεση εξωτερικών κενών
-- TRIM: αφαιρεί τα κενά από την αρχή και το τέλος.
-- Αναμενόμενο: Oracle
BEGIN
    DBMS_OUTPUT.PUT_LINE(TRIM('  Oracle  '));
END;
/

-- ΠΑΡΑΔΕΙΓΜΑ 38: Στρογγυλοποίηση
-- ROUND: στρογγυλοποιεί σε δύο δεκαδικά ψηφία.
-- Αναμενόμενο: 12.35 ή 12,35 ανάλογα με τις ρυθμίσεις
BEGIN
    DBMS_OUTPUT.PUT_LINE(ROUND(12.345, 2));
END;
/

-- ΠΑΡΑΔΕΙΓΜΑ 39: Σημερινή ημερομηνία
-- SYSDATE: ημερομηνία και ώρα του server. TO_CHAR με μορφή DD/MM/YYYY: ημέρα/μήνας/έτος.
-- Αναμενόμενο: Η τρέχουσα ημερομηνία του server
BEGIN
    DBMS_OUTPUT.PUT_LINE(TO_CHAR(SYSDATE, 'DD/MM/YYYY'));
END;
/

-- =================================================================
-- ΕΝΟΤΗΤΑ Ζ Πρώτη διαχείριση σφάλματος
-- =================================================================

-- ΠΑΡΑΔΕΙΓΜΑ 40: Διαίρεση με μηδέν
-- EXCEPTION: τμήμα χειρισμού σφαλμάτων. ZERO_DIVIDE: το συγκεκριμένο σφάλμα διαίρεσης με μηδέν.
-- Αναμενόμενο: Δεν μπορώ να διαιρέσω με μηδέν.
DECLARE
    v_divisor NUMBER := 0;
    v_result NUMBER;
BEGIN
    v_result := 10 / v_divisor;
    DBMS_OUTPUT.PUT_LINE(v_result);
EXCEPTION
    WHEN ZERO_DIVIDE THEN
        DBMS_OUTPUT.PUT_LINE('Δεν μπορώ να διαιρέσω με μηδέν.');
END;
/

